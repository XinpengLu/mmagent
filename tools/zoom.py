"""Zoom tool definition.

Zoom is a constrained Python-backed image inspection tool. It shares the same
Jupyter execution engine as code_interpreter but labels produced images as
observation_N so downstream prompts can distinguish zoomed regions.
"""

from tools.jupyter_tool_base import JupyterKernelToolBase
from tools.tool_registry import register_tool


@register_tool("zoom")
class ZoomTool(JupyterKernelToolBase):
    name = "zoom"
    tool_log_name = "ZoomTool"
    output_image_prefix = "observation"
    default_base_dir = "/tmp/zoom"
    auto_capture_pil_variables = False

    description = """
Zoom into specific image regions by writing Python code to crop and inspect
details in a stateful Jupyter kernel.

Primary use cases:
- Crop a region of interest from original_image or a prior tool image.
- Enlarge, annotate, or lightly preprocess a crop for visual inspection.
- Return or save the cropped region so it is visible in the next turn.

Image variables:
- original_image / original_image_N: original input images as PIL Image objects.
- observation_N: prior zoom outputs.
- tool_image_N: images generated by code_interpreter calls.

Visualization:
- Return the cropped image, use plt.show(), or save it.
- Do not use image.show().
- Displayed or saved images will be available as observation_N in the next turn.
"""

    parameters = {
        "type": "object",
        "properties": {
            "code": {
                "type": "string",
                "description": "Python code to crop or inspect image regions",
            }
        },
        "required": ["code"],
    }
