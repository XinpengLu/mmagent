"""Code interpreter tool definition.

The Jupyter kernel execution engine lives in jupyter_tool_base.py. This module
only declares the public tool schema and CodeInterpreter-specific behavior.
"""

from tools.jupyter_tool_base import JupyterKernelToolBase
from tools.tool_registry import register_tool


@register_tool("code_interpreter")
class CodeInterpreter(JupyterKernelToolBase):
    name = "code_interpreter"
    tool_log_name = "CodeInterpreter"
    output_image_prefix = "tool_image"
    default_base_dir = "/tmp/code_interpreter"
    auto_capture_pil_variables = True

    description = """
Executes Python code in a stateful Jupyter kernel and returns results.

Capabilities:
- Use PIL, NumPy, OpenCV, Matplotlib, SciPy, scikit-image, Pandas, or SymPy.
- Process/analyze images, calculate measurements, and create visual checks.
- Code execution is persistent within this tool instance.

Image variables:
- original_image / original_image_N: original input images as PIL Image objects.
- tool_image_N: images generated by previous code_interpreter calls.
- observation_N: images generated by zoom tool calls.

Visualization:
- To show generated images, return the object, use plt.show(), or save it.
- Do not use image.show().
- Displayed or saved images will be available as tool_image_N in the next turn.
"""

    parameters = {
        "type": "object",
        "properties": {
            "code": {
                "type": "string",
                "description": "Python code to execute in the Jupyter kernel",
            }
        },
        "required": ["code"],
    }
